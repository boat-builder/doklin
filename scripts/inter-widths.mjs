// How wide Inter draws each letter, for the flowchart renderer: it sizes a box
// from its words with no page to measure them on (src/flowchart/measure.ts).
// The numbers are read from the bundled fonts rather than retyped, so a font
// update reaches the renderer by running this.
//
// Read: both bundled subsets (latin, latin-ext), upright at weights 400 and
// 600 and italic at 400, all at optical size 14 — the size the font picks for
// a diagram's 11.5–13px words (the axis starts at 14).
//
//   node scripts/inter-widths.mjs           # write src/flowchart/interWidths.ts
//   node scripts/inter-widths.mjs --check   # exit 1 when it is not what the fonts say
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as fontkit from "fontkit";

const ROOT = new URL("../", import.meta.url).pathname;
const FONTS = join(ROOT, "src/assets/fonts/inter");
const OUT = join(ROOT, "src/flowchart/interWidths.ts");
const check = process.argv.includes("--check");

const SUBSETS = ["latin", "latin-ext"];
const STYLES = [
  { name: "REGULAR", file: "normal", wght: 400 },
  { name: "SEMIBOLD", file: "normal", wght: 600 },
  { name: "ITALIC", file: "italic", wght: 400 },
];

/** style name → (code point → advance in font units). */
const tables = new Map();
let unitsPerEm = null;
for (const style of STYLES) {
  const widths = new Map();
  for (const subset of SUBSETS) {
    const font = fontkit.openSync(join(FONTS, `inter-${subset}-opsz-${style.file}.woff2`));
    if (unitsPerEm !== null && font.unitsPerEm !== unitsPerEm) throw new Error("the Inter files disagree on units per em");
    unitsPerEm = font.unitsPerEm;
    const cut = font.getVariation({ wght: style.wght, opsz: 14 });
    for (const cp of font.characterSet) {
      // Controls draw nothing; the byte order mark is not a letter.
      if (cp < 0x20 || cp === 0x7f || cp === 0xfeff) continue;
      widths.set(cp, Math.round(cut.glyphForCodePoint(cp).advanceWidth));
    }
  }
  tables.set(style.name, widths);
}

// One list of letters for all three styles: a letter a style lacks would shift
// every index after it.
const points = [...tables.get("REGULAR").keys()].sort((a, b) => a - b);
for (const [name, widths] of tables) {
  if (widths.size !== points.length || points.some((cp) => !widths.has(cp))) {
    throw new Error(`Inter ${name.toLowerCase()} does not cover the same letters as the regular cut`);
  }
}

// The letters as runs of consecutive code points: first, count, first, count…
const runs = [];
for (const cp of points) {
  if (runs.length && runs[runs.length - 2] + runs[runs.length - 1] === cp) runs[runs.length - 1] += 1;
  else runs.push(cp, 1);
}

const lines = (numbers) => {
  const out = [];
  for (let i = 0; i < numbers.length; i += 20) out.push(`  ${numbers.slice(i, i + 20).join(", ")},`);
  return out.join("\n");
};

let text = `// Generated by scripts/inter-widths.mjs from src/assets/fonts/inter. Never
// edited by hand: run the script again when the fonts change.

/** Font units in one em. */
export const UNITS_PER_EM = ${unitsPerEm};

/** The letters the tables cover, as runs of code points: first, count, first, count… */
export const RUNS: readonly number[] = [
${lines(runs)}
];
`;
for (const style of STYLES) {
  text += `
/** Advance widths in font units, one per letter in RUNS order: weight ${style.wght}${style.file === "italic" ? " italic" : ""}. */
export const ${style.name}: readonly number[] = [
${lines(points.map((cp) => tables.get(style.name).get(cp)))}
];
`;
}

if (check) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
    console.error("src/flowchart/interWidths.ts is not what the bundled Inter says. Run: node scripts/inter-widths.mjs");
    process.exit(1);
  }
  console.log(`interWidths.ts matches the fonts (${points.length} letters).`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote src/flowchart/interWidths.ts (${points.length} letters, ${text.length} bytes)`);
}
